const path = require("path");
const dotenv = require("dotenv");

dotenv.config({ path: path.resolve(__dirname, ".env.test") });

const TEST_DB_URI =
  process.env.MONGODB_TEST_URI || "mongodb://127.0.0.1:27017/saga_elite_test";

// Force the seed script (which reads MONGO_DB_URI) to use the test database.
process.env.MONGO_DB_URI = TEST_DB_URI;
process.env.NODE_ENV = "test";

const COLLECTIONS_TO_RESET = [
  "users",
  "products",
  "orders",
  "reviews",
  "drops",
  "coupons",
  "usercoupons",
  "smartalerts",
  "adminlogs",
  "notifications",
  "manualpayments",
  "newslettersubscribers",
  "contacts",
  "carts",
  "wishlists",
];

const dropCollections = async (mongoose) => {
  const conn = mongoose.connection;
  for (const name of COLLECTIONS_TO_RESET) {
    try {
      await conn.db.collection(name).deleteMany({});
    } catch (err) {
      // Collection may not exist on a fresh DB — ignore.
      if (!/ns not found/i.test(String(err.message))) {
        console.warn(`[e2e setup] could not clear ${name}:`, err.message);
      }
    }
  }
};

