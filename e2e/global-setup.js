module.exports = async () => {
  const mongoose = require(path.resolve(
    __dirname,
    "../Server-side/node_modules/mongoose"
  ));

  console.log("[e2e setup] connecting to", TEST_DB_URI);
  await mongoose.connect(TEST_DB_URI);

  console.log("[e2e setup] resetting collections");
  await dropCollections(mongoose);

  await mongoose.disconnect();

  // Run seed-demo-admins as a black box (it manages its own connection).
  const { seedDemoAdmins } = require(path.resolve(
    __dirname,
    "../Server-side/scripts/seed-demo-admins.js"
  ));
  console.log("[e2e setup] seeding demo admins");
  await seedDemoAdmins();

  // Reconnect to add fixtures.
  await mongoose.connect(TEST_DB_URI);
  console.log("[e2e setup] seeding test fixtures");
  await seedFixtures(mongoose);
  await mongoose.disconnect();

  console.log("[e2e setup] complete");
};
